"""End-to-end experiment: validation, model comparison, explanation and spatial explanation.

:func:`run_experiment` executes the full GeoExplain workflow from one configuration and
writes tables, figures, rasters, a reproducibility record and an ``experiment.json`` index
that :func:`geoxplain.workflows.report.build_report` turns into an HTML report.
"""

from __future__ import annotations

import json
import logging
import time
from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from .. import visualization as viz
from .._version import __version__
from ..datasets.synthetic import FEATURE_LABELS
from ..explainers import GeoShapExplainer, builtin_importance, partial_dependence, permutation_importance
from ..io.raster import load_raster_source
from ..io.tabular import GeoDataset, load_dataset, save_table, save_tables_excel
from ..metrics import confusion, evaluate_model
from ..models import GeoExplainModel, resolve_algorithm
from ..spatial import compute_spatial_shap
from ..utils import environment_info, set_global_seed, write_json
from ..utils.exceptions import DataValidationError
from ..validation import (
    SpatialBlockKFold,
    compare_validation_strategies,
    default_block_size,
    morans_i,
    random_split,
    spatial_split,
)
from ..validation.evaluate import HIGHER_IS_BETTER

log = logging.getLogger("geoxplain")

DEFAULT_MODELS = ["random_forest", "xgboost", "lightgbm", "mlp", "logistic_regression"]


@dataclass
class ExperimentConfig:
    """Configuration of :func:`run_experiment` (JSON-serialisable)."""

    data: str
    target: str = "target"
    features: list[str] | None = None
    task: str | None = None
    x: str = "x"
    y: str = "y"
    id_col: str | None = "id"
    crs: str | None = None
    raster: str | None = None
    models: list[str] = field(default_factory=lambda: list(DEFAULT_MODELS))
    primary_model: str = "random_forest"
    out_dir: str = "results/example_run"
    seed: int = 42
    n_splits: int = 5
    test_size: float = 0.25
    block_size: float | None = None
    buffer: float = 0.0
    shap_samples: int = 400
    class_label: Any = None
    model_params: dict[str, dict[str, Any]] = field(default_factory=dict)
    formats: list[str] = field(default_factory=lambda: ["png"])
    dataset_label: str = "Synthetic example data generated by GeoExplain (not real observations)"
    target_label: str = "target"
    feature_labels: dict[str, str] = field(default_factory=lambda: dict(FEATURE_LABELS))

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_json(cls, path: str | Path) -> "ExperimentConfig":
        payload = json.loads(Path(path).read_text())
        known = {k: v for k, v in payload.items() if k in cls.__dataclass_fields__}
        return cls(**known)


def _make_model(name: str, task: str, cfg: ExperimentConfig) -> GeoExplainModel:
    key = resolve_algorithm(name)
    return GeoExplainModel(key, task, params=cfg.model_params.get(key), random_state=cfg.seed)


def _rel(path: Path, root: Path) -> str:
    return str(path.relative_to(root)).replace("\\", "/")


def _metric_lists(task: str) -> list[str]:
    return ["accuracy", "f1", "roc_auc", "pr_auc"] if task == "classification" else ["r2", "rmse", "mae"]


def _holdout_score(model: GeoExplainModel, X: pd.DataFrame) -> np.ndarray:
    return model.predict_proba(X)[:, model.class_index(None)] if model.task == "classification" else model.predict(X)


def run_experiment(config: ExperimentConfig) -> dict[str, Any]:
    """Run the complete workflow and return the experiment index (also saved as JSON)."""
    t0 = time.time()
    cfg = config
    set_global_seed(cfg.seed)
    out = Path(cfg.out_dir)
    for sub in ("tables", "figures", "rasters", "models"):
        (out / sub).mkdir(parents=True, exist_ok=True)
    fmts = tuple(cfg.formats)
    viz.apply_style()
    notes: list[str] = []
    figures: dict[str, str] = {}
    tables: dict[str, str] = {}
    sheets: dict[str, pd.DataFrame] = {}

    def fig_done(key: str, fig: plt.Figure | None, stem: Path) -> None:
        if fig is not None:
            plt.close(fig)
        figures[key] = _rel(stem.with_suffix(".png"), out)

    def table_done(key: str, df: pd.DataFrame, index: bool = False) -> None:
        save_table(df, out / "tables" / f"{key}.csv", index=index)
        tables[key] = f"tables/{key}.csv"
        sheets[key[:31]] = df.reset_index() if index else df

    # ---------------------------------------------------------------- 1. data
    log.info("Loading dataset %s", cfg.data)
    ds: GeoDataset = load_dataset(cfg.data, cfg.target, cfg.features, x=cfg.x, y=cfg.y, id_col=cfg.id_col,
                                  task=cfg.task, crs=cfg.crs)
    task = ds.task
    coords = ds.require_coords()
    summary = ds.summary()
    y_num = pd.Series(pd.factorize(ds.y)[0] if task == "classification" else ds.y.to_numpy(), dtype=float)
    summary["target_morans_i"] = morans_i(y_num.to_numpy(), coords, permutations=99, random_state=cfg.seed)
    block = cfg.block_size or default_block_size(coords, cfg.n_splits)
    summary["block_size_used"] = float(block)
    models = [resolve_algorithm(m) for m in cfg.models]
    primary = resolve_algorithm(cfg.primary_model)
    if primary not in models:
        models.insert(0, primary)

    # ---------------------------------------------------------------- 2. hold-out (random vs spatial)
    strat = ds.y.to_numpy() if task == "classification" else None
    r_tr, r_te = random_split(len(ds.X), cfg.test_size, cfg.seed, stratify=strat)
    s_tr, s_te = spatial_split(coords, cfg.test_size, block, cfg.seed, cfg.buffer)
    splits = {"random_split": (r_tr, r_te), "spatial_split": (s_tr, s_te)}
    holdout_rows: list[dict[str, Any]] = []
    fitted: dict[str, GeoExplainModel] = {}  # models trained on the spatial training block
    for name in models:
        for sname, (tr, te) in splits.items():
            m = _make_model(name, task, cfg).fit(ds.X.iloc[tr], ds.y.iloc[tr])
            row = {"model": name, "strategy": sname, "n_train": len(tr), "n_test": len(te)}
            row.update(evaluate_model(m, ds.X.iloc[te], ds.y.iloc[te]))
            holdout_rows.append(row)
            if sname == "spatial_split":
                fitted[name] = m
        log.info("hold-out done: %s", name)
    holdout = pd.DataFrame(holdout_rows)
    table_done("holdout_metrics", holdout)
    spatial_tab = holdout[holdout.strategy == "spatial_split"].set_index("model")
    fig = viz.plot_metric_comparison(spatial_tab, _metric_lists(task), path=out / "figures" / "model_performance",
                                     title="Model performance on a spatially held-out block", formats=fmts)
    fig_done("model_performance", fig, out / "figures" / "model_performance")

    # ---------------------------------------------------------------- 3. cross-validation
    folds_all, sums = [], []
    for name in models:
        res = compare_validation_strategies(_make_model(name, task, cfg), ds, n_splits=cfg.n_splits,
                                            block_size=block, buffer=cfg.buffer, seed=cfg.seed)
        f = res.folds.copy()
        f.insert(0, "model", name)
        folds_all.append(f)
        s = res.summary.copy()
        s.columns = [f"{a}_{b}" for a, b in s.columns]
        s.insert(0, "model", name)
        sums.append(s.reset_index())
        log.info("cross-validation done: %s", name)
    folds = pd.concat(folds_all, ignore_index=True)
    cv_summary = pd.concat(sums, ignore_index=True)
    table_done("cv_folds", folds)
    table_done("cv_summary", cv_summary)
    metrics_cv = _metric_lists(task)
    opt_rows = []
    for name in models:
        sub = folds[folds.model == name].groupby("strategy")[metrics_cv].mean()
        if {"random_kfold", "spatial_block_cv"} <= set(sub.index):
            for met in metrics_cv:
                gap = sub.loc["random_kfold", met] - sub.loc["spatial_block_cv", met]
                if not HIGHER_IS_BETTER.get(met, True):
                    gap = -gap
                opt_rows.append({"model": name, "metric": met, "random_kfold": sub.loc["random_kfold", met],
                                 "spatial_block_cv": sub.loc["spatial_block_cv", met], "optimism": gap})
    table_done("validation_optimism", pd.DataFrame(opt_rows))
    fig = viz.plot_validation_comparison(folds, ["roc_auc", "pr_auc"] if task == "classification" else ["r2", "rmse"],
                                         path=out / "figures" / "validation_comparison", formats=fmts)
    fig_done("validation_comparison", fig, out / "figures" / "validation_comparison")
    fold_ids = SpatialBlockKFold(cfg.n_splits, block, random_state=cfg.seed).fold_assignments(coords)
    fig = viz.plot_fold_map(coords, fold_ids, path=out / "figures" / "cv_folds", formats=fmts)
    fig_done("cv_folds", fig, out / "figures" / "cv_folds")

    # ---------------------------------------------------------------- 4. comparison figures (spatial hold-out)
    Xte, yte = ds.X.iloc[s_te], ds.y.iloc[s_te]
    if task == "classification":
        classes = list(fitted[primary].classes_)
        curves = {n: (yte.to_numpy(), m.predict_proba(Xte)[:, 1]) for n, m in fitted.items()}
        pos = classes[1]
        fig = viz.plot_roc_pr_curves(curves, positive_label=pos, path=out / "figures" / "roc_pr_curves", formats=fmts)
        fig_done("roc_pr_curves", fig, out / "figures" / "roc_pr_curves")
        cms = {n: confusion(yte, m.predict(Xte), classes) for n, m in fitted.items()}
        fig = viz.plot_confusion_matrices(cms, classes, path=out / "figures" / "confusion_matrices", formats=fmts)
        fig_done("confusion_matrices", fig, out / "figures" / "confusion_matrices")
    shap_rows = {}
    rng = np.random.default_rng(cfg.seed)
    sub_idx = rng.choice(len(Xte), size=min(cfg.shap_samples // 2, len(Xte)), replace=False)
    for name, m in fitted.items():
        try:
            bg = ds.X.iloc[s_tr].sample(min(60, len(s_tr)), random_state=cfg.seed)
            sv = GeoShapExplainer(m, background=bg, class_label=cfg.class_label, random_state=cfg.seed).explain(
                Xte.iloc[sub_idx])
            shap_rows[name] = sv.mean_abs().set_index("feature")["share"]
        except Exception as exc:  # noqa: BLE001
            notes.append(f"SHAP comparison unavailable for {name}: {exc}")
    if shap_rows:
        imp_cmp = pd.DataFrame(shap_rows).reindex(ds.feature_names)
        table_done("shap_importance_by_model", imp_cmp, index=True)
        fig = viz.plot_importance_comparison(imp_cmp, path=out / "figures" / "feature_importance_comparison",
                                             formats=fmts)
        fig_done("feature_importance_comparison", fig, out / "figures" / "feature_importance_comparison")

    # ---------------------------------------------------------------- 5. permutation importance (held-out)
    perm = permutation_importance(fitted[primary], Xte, yte, n_repeats=10, random_state=cfg.seed)
    table_done("permutation_importance", perm)
    fig = viz.plot_importance(perm, path=out / "figures" / "feature_importance", formats=fmts,
                              title="Permutation importance on the spatial hold-out block",
                              xlabel=f"Decrease in {perm['scoring'].iloc[0]} when the feature is shuffled")
    fig_done("feature_importance", fig, out / "figures" / "feature_importance")
    try:
        table_done("builtin_importance", builtin_importance(fitted[primary]))
    except Exception as exc:  # noqa: BLE001
        notes.append(f"Built-in importance unavailable: {exc}")

    # ---------------------------------------------------------------- 6. final model + global/local SHAP
    final = _make_model(primary, task, cfg).fit(ds.X, ds.y)
    final.save(out / "models" / f"{primary}.joblib")
    background = ds.X.sample(min(100, len(ds.X)), random_state=cfg.seed)
    explainer = GeoShapExplainer(final, background=background, class_label=cfg.class_label, random_state=cfg.seed)
    n_shap = min(cfg.shap_samples, len(ds.X))
    shap_idx = np.sort(rng.choice(len(ds.X), size=n_shap, replace=False))
    sv = explainer.explain(ds.X.iloc[shap_idx])
    add = explainer.check_additivity(sv)
    table_done("shap_global", sv.mean_abs())
    pts = pd.concat([ds.ids.iloc[shap_idx].reset_index(drop=True), ds.coords.iloc[shap_idx].reset_index(drop=True),
                     sv.to_frame(include_data=False).reset_index(drop=True)], axis=1)
    save_table(pts, out / "tables" / "shap_values_points.csv")
    tables["shap_values_points"] = "tables/shap_values_points.csv"
    fig = viz.plot_shap_summary(sv, path=out / "figures" / "shap_summary", formats=fmts)
    fig_done("shap_summary", fig, out / "figures" / "shap_summary")
    fig = viz.plot_shap_bar(sv, path=out / "figures" / "shap_bar", formats=fmts)
    fig_done("shap_bar", fig, out / "figures" / "shap_bar")
    top = sv.mean_abs()["feature"].tolist()
    for feat in top[:3]:
        second = next(f for f in top if f != feat)
        fig = viz.plot_shap_dependence(sv, feat, color_by=second, path=out / "figures" / f"shap_dependence_{feat}",
                                       formats=fmts)
        fig_done(f"shap_dependence_{feat}", fig, out / "figures" / f"shap_dependence_{feat}")
    pdps = [partial_dependence(final, ds.X, f, class_label=cfg.class_label, random_state=cfg.seed) for f in top[:6]]
    fig = viz.plot_partial_dependence(pdps, path=out / "figures" / "partial_dependence", formats=fmts)
    fig_done("partial_dependence", fig, out / "figures" / "partial_dependence")
    out_vals = sv.reconstructed_output
    local_ids = [int(np.argmax(out_vals)), int(np.argmin(out_vals)), int(np.argsort(np.abs(out_vals - np.median(out_vals)))[0])]
    local_tables = []
    for k, li in enumerate(dict.fromkeys(local_ids)):
        fig = viz.plot_waterfall(sv, li, path=out / "figures" / f"local_waterfall_{k + 1}", formats=fmts)
        fig_done(f"local_waterfall_{k + 1}", fig, out / "figures" / f"local_waterfall_{k + 1}")
        loc = sv.local(li)
        loc.insert(0, "observation", int(ds.ids.iloc[shap_idx[li]]) if pd.api.types.is_numeric_dtype(ds.ids) else str(ds.ids.iloc[shap_idx[li]]))
        local_tables.append(loc)
        if k == 0:
            try:
                fig = viz.plot_force(sv, li, path=out / "figures" / "local_force_1", formats=fmts)
                fig_done("local_force_1", fig, out / "figures" / "local_force_1")
            except Exception as exc:  # noqa: BLE001
                plt.close("all")
                notes.append(f"Force plot unavailable: {exc}")
    table_done("local_explanations", pd.concat(local_tables, ignore_index=True))
    moran_rows = []
    for j, feat in enumerate(sv.feature_names):
        mi = morans_i(sv.values[:, j], ds.coords.iloc[shap_idx].to_numpy(), permutations=99, random_state=cfg.seed)
        moran_rows.append({"feature": feat, "morans_i_of_shap": mi["I"], "p_value": mi["p_value"], "n": mi["n"]})
    table_done("shap_spatial_autocorrelation", pd.DataFrame(moran_rows))

    # ---------------------------------------------------------------- 7. spatial explainability on the raster
    rasters: dict[str, str] = {}
    spatial_summary = None
    spatial_meta: dict[str, Any] = {}
    if cfg.raster:
        stack = load_raster_source(cfg.raster, names=final.feature_names_)
        res = compute_spatial_shap(final, stack, background=background, class_label=cfg.class_label,
                                   feature_labels=cfg.feature_labels, random_state=cfg.seed)
        written = res.write(out / "rasters")
        rasters = {k: _rel(v, out) for k, v in written.items()}
        spatial_summary = res.summary_table()
        table_done("spatial_shap_summary", spatial_summary)
        spatial_meta = {"additivity": res.additivity, "uncertainty_method": res.uncertainty_method,
                        "uncertainty_description": res.uncertainty_description, "notes": res.notes,
                        "stack": stack.describe()}
        src = cfg.dataset_label
        label = cfg.target_label
        fig = viz.plot_map(res.prediction, stack, f"Predicted {label}", "Predicted probability"
                           if task == "classification" else "Predicted value", vmin=0 if task == "classification" else None,
                           vmax=1 if task == "classification" else None, source=src,
                           path=out / "figures" / "spatial_prediction", formats=fmts)
        fig_done("spatial_prediction", fig, out / "figures" / "spatial_prediction")
        fig = viz.plot_shap_panels(res, path=out / "figures" / "spatial_shap_panels", source=src, formats=fmts)
        fig_done("spatial_shap_panels", fig, out / "figures" / "spatial_shap_panels")
        maps = viz.save_all_shap_maps(res, out / "figures" / "maps", source=src, formats=fmts)
        for feat, p in maps.items():
            figures[f"map_{feat}_shap"] = _rel(p, out)
        fig = viz.plot_prediction_uncertainty(res, path=out / "figures" / "spatial_uncertainty_explanation",
                                              source=src, formats=fmts)
        fig_done("spatial_uncertainty_explanation", fig, out / "figures" / "spatial_uncertainty_explanation")
        top_feat = spatial_summary.sort_values("mean_abs_shap", ascending=False)["feature"].iloc[0]
        fig = viz.plot_feature_and_shap(res, top_feat, path=out / "figures" / "feature_vs_spatial_shap",
                                        source=src, formats=fmts)
        fig_done("feature_vs_spatial_shap", fig, out / "figures" / "feature_vs_spatial_shap")
        notes.extend(res.notes)
    else:
        notes.append("No raster stack supplied: spatial SHAP rasters were not produced.")

    # ---------------------------------------------------------------- 8. records
    sheets_ordered = {k: v for k, v in sheets.items()}
    save_tables_excel(sheets_ordered, out / "tables" / "all_results.xlsx", index=False)
    tables["all_results_xlsx"] = "tables/all_results.xlsx"
    env = environment_info()
    repro = {"seed": cfg.seed, "environment": env, "config": cfg.to_dict(),
             "model_configs": {n: fitted[n].get_config() for n in fitted},
             "final_model": final.get_config(), "splits": {"random_test": int(len(r_te)), "spatial_test": int(len(s_te)),
                                                          "spatial_train_after_buffer": int(len(s_tr))},
             "block_size": float(block)}
    write_json(out / "reproducibility.json", repro)
    index = {
        "geoxplain_version": __version__,
        "created_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "runtime_seconds": round(time.time() - t0, 1),
        "task": task, "primary_model": primary, "models": models, "dataset_label": cfg.dataset_label,
        "config": cfg.to_dict(), "dataset": summary, "tables": tables, "figures": figures, "rasters": rasters,
        "shap_additivity": add, "shap_output_space": sv.output_space, "spatial": spatial_meta,
        "reproducibility": repro, "notes": notes,
    }
    write_json(out / "experiment.json", index)
    log.info("Experiment finished in %.1fs -> %s", time.time() - t0, out)
    if not models:
        raise DataValidationError("No models were run.")
    return index
